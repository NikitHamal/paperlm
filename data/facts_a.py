"""PaperLM closed-world fact classes (source of truth for the verified "fact" tier).

Why this exists: a 10M-parameter model cannot *know* facts, so PaperLM never asks it to.  Knowledge lives here as
closed-world tables, one row per (key, value, definition).  Every question the fact tier can emit is derived from a
single row and its distractors are the values of *other* rows of the same class, so:

  * the answer is correct by construction (it is the stored value of the row),
  * each distractor is wrong by construction (it is another row's value, and rows of a class are mutually exclusive),
  * nothing is invented at generation time: no free text, no free numbers, no paraphrase.

A class is a table with a question form `qa` (asks for the value, given the key), an optional reverse form `qb`
(asks for the key, given the value) and an open form `qo` (a written question answered by `def`).  `qb` is only
emitted when the class's values are unique, because a value shared by two rows would make the reverse question
ambiguous.

Sources are named per class (`src`).  Only standard textbook statements are used.
"""


def K(cid, subjects, units, label, qa, qb, qo, src, pairs):
    """Build one fact class.  pairs = [(key, value, definition)]."""
    return dict(id=cid, subjects=subjects, units=units, label=label, qa=qa, qb=qb, qo=qo, src=src,
                pairs=[list(p) for p in pairs])


